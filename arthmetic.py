a = 10
b = 3

# Addition (+)
print(a + b)       # 10 + 3 = 13

# Subtraction (-)
print(a - b)       # 10 - 3 = 7

# Multiplication (*)
print(a * b)       # 10 × 3 = 30

# Division (/)
print(a / b)       # 10 ÷ 3 = 3.333...

# Floor Division (//)
print(a // b)      # Gives only the whole-number part = 3

# Modulus (%)
print(a % b)       # Gives remainder = 1

# Exponent / Power (**)
print(a ** b)      # 10³ = 1000