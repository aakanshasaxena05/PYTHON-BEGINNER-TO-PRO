# BODMAS example in Python

result = (10 + 5) ** 2 / 5 * 2 - 10

# B = Brackets
# (10 + 5) = 15

# O = Order / Power
# 15 ** 2 = 225

# D = Division
# 225 / 5 = 45

# M = Multiplication
# 45 * 2 = 90

# A = Addition
# Addition was already performed inside the brackets: 10 + 5 = 15

# S = Subtraction
# 90 - 10 = 80

print(result)